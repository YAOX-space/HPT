function codeText = pll_dq_controller_code()
codeText = strjoin({ ...
    ['function [m_ref6, ctrl_dbg] = fcn(Vabc, ts, grid_f0, vref_lv, ', ...
    'vreg_kp, vreg_ki, m_max, reg_polarity, open_amp, open_phase, ', ...
    'pll_kp, pll_ki, inj_phase, swell_gain, swell_phase, swell_mmax)'], ...
    '%#codegen', ...
    'persistent theta xi_pll xi_a xi_b xi_c t_ctrl v_rms_f', ...
    'if isempty(theta)', ...
    '    theta = 0;', ...
    '    xi_pll = 0;', ...
    '    xi_a = 0;', ...
    '    xi_b = 0;', ...
    '    xi_c = 0;', ...
    '    t_ctrl = 0;', ...
    '    v_rms_f = 0;', ...
    'end', ...
    't_ctrl = t_ctrl + ts;', ...
    'm_ref6 = zeros(6, 1);', ...
    'ctrl_dbg = zeros(7, 1);', ...
    'va = Vabc(1);', ...
    'vb = Vabc(2);', ...
    'vc = Vabc(3);', ...
    'alpha = (2/3) * (va - 0.5*vb - 0.5*vc);', ...
    'beta = (sqrt(3)/3) * (vb - vc);', ...
    'theta_meas = atan2(beta, alpha);', ...
    'pll_err = atan2(sin(theta_meas - theta), cos(theta_meas - theta));', ...
    'xi_pll = xi_pll + pll_ki * pll_err * ts;', ...
    'omega = 2*pi*grid_f0 + pll_kp * pll_err + xi_pll;', ...
    'theta = theta + omega * ts;', ...
    'theta = theta - 2*pi*floor(theta/(2*pi));', ...
    'ct = cos(theta);', ...
    'st = sin(theta);', ...
    'vd = alpha*ct + beta*st;', ...
    'vq = -alpha*st + beta*ct;', ...
    'v_rms = sqrt(max((va*va + vb*vb + vc*vc) / 3, 0));', ...
    'if v_rms_f == 0', ...
    '    v_rms_f = v_rms;', ...
    'end', ...
    'alpha_v = min(max(ts / 0.005, 0), 1);', ...
    'v_rms_f = v_rms_f + alpha_v * (v_rms - v_rms_f);', ...
    'v_meas = v_rms_f;', ...
    'if open_amp > 0', ...
    '    mo = min(max(open_amp, 0), m_max);', ...
    '    oa = mo*cos(theta + open_phase);', ...
    '    ob = mo*cos(theta - 2*pi/3 + open_phase);', ...
    '    oc = mo*cos(theta + 2*pi/3 + open_phase);', ...
    '    m_amp = sqrt((oa*oa + ob*ob + oc*oc) / 3);', ...
    '    m_ref6 = reg_polarity * [oa; -oa; ob; -ob; oc; -oc];', ...
    '    ctrl_dbg = [theta; vd; vq; v_meas; vref_lv - v_meas; m_amp; open_phase];', ...
    '    return;', ...
    'end', ...
    'v_err = vref_lv - v_meas;', ...
    'err_pu = v_err / max(vref_lv, 1e-6);', ...
    'phi = inj_phase;', ...
    'm_limit = m_max;', ...
    'if abs(err_pu) < 0.002', ...
    '    kp_eff = 0;', ...
    '    ki_eff = 0;', ...
    '    xi_a = 0;', ...
    '    xi_b = 0;', ...
    '    xi_c = 0;', ...
    '    err_eff = 0;', ...
    'elseif err_pu >= 0', ...
    '    kp_eff = abs(vreg_kp);', ...
    '    ki_eff = abs(vreg_ki);', ...
    '    err_eff = err_pu;', ...
    '    phi = inj_phase;', ...
    '    m_limit = m_max;', ...
    'else', ...
    '    kp_eff = abs(vreg_kp) * swell_gain;', ...
    '    ki_eff = abs(vreg_ki) * swell_gain;', ...
    '    err_eff = err_pu;', ...
    '    phi = swell_phase;', ...
    '    m_limit = min(abs(swell_mmax), m_max);', ...
    '    if kp_eff == 0 && ki_eff == 0', ...
    '        xi_a = 0;', ...
    '        xi_b = 0;', ...
    '        xi_c = 0;', ...
    '    end', ...
    'end', ...
    'if t_ctrl > 0.02', ...
    '    xi_a = xi_a + ki_eff * err_eff * ts;', ...
    'else', ...
    '    xi_a = 0;', ...
    'end', ...
    'm_unsat = kp_eff * err_eff + xi_a;', ...
    'm_cmd = min(max(m_unsat, -m_limit), m_limit);', ...
    'if m_cmd ~= m_unsat', ...
    '    xi_a = m_cmd - kp_eff * err_eff;', ...
    'end', ...
    'ma = m_cmd * sin(theta + phi);', ...
    'mb = m_cmd * sin(theta + phi - 2*pi/3);', ...
    'mc = m_cmd * sin(theta + phi + 2*pi/3);', ...
    'm_amp = sqrt((ma*ma + mb*mb + mc*mc) / 3);', ...
    'm_ref6 = reg_polarity * [ma; -ma; mb; -mb; mc; -mc];', ...
    'ctrl_dbg = [theta; vd; vq; v_meas; v_err; m_amp; phi];', ...
    'end' ...
    }, newline);
end

function codeText = energy_controller_code()
codeText = strjoin({ ...
    ['function [m_abc, dbg] = fcn(vdc, Vabc, Iabc, ts, grid_f0, vdc_ref, ', ...
    'vdc_kp, vdc_ki, id_max, cur_kp, cur_ki, mmax, pll_kp, pll_ki, ', ...
    'vff_gain, control_sign, polarity)'], ...
    '%#codegen', ...
    'persistent theta xi_pll xi_vdc xi_id xi_iq t_ctrl vmag_nom hvrt_latch', ...
    'if isempty(theta)', ...
    '    theta = 0;', ...
    '    xi_pll = 0;', ...
    '    xi_vdc = 0;', ...
    '    xi_id = 0;', ...
    '    xi_iq = 0;', ...
    '    t_ctrl = 0;', ...
    '    vmag_nom = 0;', ...
    '    hvrt_latch = 0;', ...
    'end', ...
    't_ctrl = t_ctrl + ts;', ...
    'va = Vabc(1); vb = Vabc(2); vc = Vabc(3);', ...
    'ia = Iabc(1); ib = Iabc(2); ic = Iabc(3);', ...
    'valpha = (2/3) * (va - 0.5*vb - 0.5*vc);', ...
    'vbeta = (sqrt(3)/3) * (vb - vc);', ...
    'vmag = sqrt(valpha*valpha + vbeta*vbeta);', ...
    'if t_ctrl < 0.02', ...
    '    if vmag_nom == 0; vmag_nom = vmag; else; vmag_nom = 0.98*vmag_nom + 0.02*vmag; end', ...
    'end', ...
    'if vmag_nom <= 1; vmag_nom = max(vmag, 1); end', ...
    'if vdc > 1.35 * vdc_ref', ...
    '    hvrt_latch = 1;', ...
    'elseif hvrt_latch >= 0.5 && vmag < 1.01 * vmag_nom && abs(vdc - vdc_ref) < 25', ...
    '    hvrt_latch = 0;', ...
    'end', ...
    'eff_control_sign = control_sign;', ...
    'eff_polarity = polarity;', ...
    'if hvrt_latch >= 0.5', ...
    '    eff_control_sign = abs(control_sign);', ...
    '    eff_polarity = abs(polarity);', ...
    'end', ...
    'ialpha = (2/3) * (ia - 0.5*ib - 0.5*ic);', ...
    'ibeta = (sqrt(3)/3) * (ib - ic);', ...
    'theta_meas = atan2(vbeta, valpha);', ...
    'pll_err = atan2(sin(theta_meas - theta), cos(theta_meas - theta));', ...
    'xi_pll = xi_pll + pll_ki * pll_err * ts;', ...
    'omega = 2*pi*grid_f0 + pll_kp * pll_err + xi_pll;', ...
    'theta = theta + omega * ts;', ...
    'theta = theta - 2*pi*floor(theta/(2*pi));', ...
    'ct = cos(theta); st = sin(theta);', ...
    'vd = valpha*ct + vbeta*st;', ...
    'vq = -valpha*st + vbeta*ct;', ...
    'id = ialpha*ct + ibeta*st;', ...
    'iq = -ialpha*st + ibeta*ct;', ...
    'err = vdc_ref - vdc;', ...
    'if abs(err) < 3 || t_ctrl < 0.02', ...
    '    xi_vdc = 0;', ...
    '    id_ref = 0;', ...
    'else', ...
    '    xi_vdc = xi_vdc + vdc_ki * err * ts;', ...
    '    id_unsat = vdc_kp * err + xi_vdc;', ...
    '    id_ref = min(max(id_unsat, -id_max), id_max);', ...
    '    if id_ref ~= id_unsat', ...
    '        xi_vdc = id_ref - vdc_kp * err;', ...
    '    end', ...
    'end', ...
    'iq_ref = 0;', ...
    'eid = id_ref - id;', ...
    'eiq = iq_ref - iq;', ...
    'xi_id = xi_id + cur_ki * eid * ts;', ...
    'xi_iq = xi_iq + cur_ki * eiq * ts;', ...
    'vd_ctrl = cur_kp * eid + xi_id;', ...
    'vq_ctrl = cur_kp * eiq + xi_iq;', ...
    'vconv_d = vff_gain * vd - eff_control_sign * vd_ctrl;', ...
    'vconv_q = vff_gain * vq - eff_control_sign * vq_ctrl;', ...
    'conv_alpha = vconv_d*ct - vconv_q*st;', ...
    'conv_beta = vconv_d*st + vconv_q*ct;', ...
    'ma_unsat = 2 * conv_alpha / max(abs(vdc), 50);', ...
    'mb_unsat = 2 * (-0.5*conv_alpha + (sqrt(3)/2)*conv_beta) / max(abs(vdc), 50);', ...
    'mc_unsat = 2 * (-0.5*conv_alpha - (sqrt(3)/2)*conv_beta) / max(abs(vdc), 50);', ...
    'ma = min(max(ma_unsat, -mmax), mmax);', ...
    'mb = min(max(mb_unsat, -mmax), mmax);', ...
    'mc = min(max(mc_unsat, -mmax), mmax);', ...
    'if abs(ma) >= mmax || abs(mb) >= mmax || abs(mc) >= mmax', ...
    '    xi_id = xi_id - cur_ki * eid * ts;', ...
    '    xi_iq = xi_iq - cur_ki * eiq * ts;', ...
    'end', ...
    'm_abc = eff_polarity * [ma; mb; mc];', ...
    'p_ac = va*ia + vb*ib + vc*ic;', ...
    'dbg = [theta; vd; vq; id; iq; id_ref; vdc; err; p_ac; ma; mb; mc];', ...
    'end' ...
    }, newline);
end

function h = ph(blk, kind, idx)
P = get_param(blk, 'PortHandles');
h = P.(kind)(idx);
end
