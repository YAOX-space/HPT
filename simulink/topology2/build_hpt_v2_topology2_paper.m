function build_hpt_v2_topology2_paper()
% build_hpt_v2_topology2_paper
% Switch-level HPT topology skeleton following the paper-style topology:
%   - Main transformer W1/W2.
%   - HBC regulating converter connected to the primary-side injection path
%     through per-phase LC filter branches.
%   - TPFBVSC energy converter connected to a secondary-side parallel
%     coupled transformer through per-phase L filters.
%   - HBC and TPFBVSC share a DC stabilized capacitor and chopper branch.
%
% Converter gates are held off by default. This is a plant/topology starting
% point; PWM, fault logic, and controller migration should be added later.

M = 'hpt_v2_topology2_paper';
if bdIsLoaded(M)
    set_param(M, 'Dirty', 'off');
    close_system(M, 0);
end
new_system(M);
load_system(M);
thisDir = fileparts(mfilename('fullpath'));
addpath(thisDir);
addpath(fileparts(thisDir));

f0 = 50;
Ts = 20e-6;
Vmv = 10e3;
Vlv = 400;
Srated = 400e3;
Saux = 120e3;
Sser = 30e3;
SserModel = 300e6;
Vaux = 400;
Vw5 = 400;
Vw6 = 100;
Rhbc = 0.03;
Lhbc = 2e-3;
Chbc = 20e-6;
Ltpf = 1.5e-3;
Cdc = 2200e-6;
Rchop = (800^2) / Saux;

Zb = Vmv^2 / Srated;
scr = 3;
Zg = Zb / scr;
Rg = Zg / sqrt(1 + 49);
Lg = 7 * Rg / (2 * pi * f0);

P = @(x, y, w, h) [x y x+w y+h];
set_param(M, 'Solver', 'ode23tb', 'StopTime', '0.2');
mw = get_param(M, 'ModelWorkspace');
assignin(mw, 'hpt_pwm_fs', 2000);
assignin(mw, 'hpt_m_energy', 0.00);
assignin(mw, 'hpt_m_reg', 0.10);
assignin(mw, 'hpt_ctrl_Ts', Ts);
assignin(mw, 'hpt_grid_f0', f0);
assignin(mw, 'hpt_vdc_ref', 800.0);
assignin(mw, 'hpt_rchop', Rchop);
assignin(mw, 'hpt_chopper_threshold', 850.0);
assignin(mw, 'hpt_vdc_kp', 2.00);
assignin(mw, 'hpt_vdc_ki', 0.20);
assignin(mw, 'hpt_energy_id_max', 20.0);
assignin(mw, 'hpt_energy_i_kp', 0.50);
assignin(mw, 'hpt_energy_i_ki', 100.0);
assignin(mw, 'hpt_m_energy_max', 0.95);
assignin(mw, 'hpt_energy_vff_gain', 1.06);
assignin(mw, 'hpt_energy_control_sign', -1.0);
assignin(mw, 'hpt_energy_bridge_polarity', -1.0);
assignin(mw, 'hpt_vref_lv', 207.0);
assignin(mw, 'hpt_vreg_kp', 20.0);
assignin(mw, 'hpt_vreg_ki', 0.0);
assignin(mw, 'hpt_m_reg_max', 0.80);
assignin(mw, 'hpt_s2_resistance', 1e-3);
assignin(mw, 'hpt_reg_polarity', 1.0);
assignin(mw, 'hpt_reg_openloop_amp', 0.0);
assignin(mw, 'hpt_reg_openloop_phase', 0.0);
assignin(mw, 'hpt_pll_kp', 80.0);
assignin(mw, 'hpt_pll_ki', 2500.0);
assignin(mw, 'hpt_inj_phase_offset', -1.05);
assignin(mw, 'hpt_swell_gain_scale', 1.0);
assignin(mw, 'hpt_swell_phase_offset', -0.50);
assignin(mw, 'hpt_swell_m_reg_max', 0.50);
assignin(mw, 'hpt_sac_enable', 0.0);
assignin(mw, 'hpt_sac_energy_enable', 0.0);
assignin(mw, 'hpt_sac_policy_mode', 0.0);
assignin(mw, 'hpt_sac_actor_select_mode', 0.0);
assignin(mw, 'hpt_sac_actor_filter_tau', 0.001);
assignin(mw, 'hpt_sac_gridnorm_startup_s', 0.030);
assignin(mw, 'hpt_sac_fault_time_norm_s', 0.50);
assignin(mw, 'hpt_sac_recovery_time_norm_s', 0.50);
assignin(mw, 'hpt_sac_phase_override_enable', 0.0);
assignin(mw, 'hpt_sac_phase_fault_start_s', 0.0);
assignin(mw, 'hpt_sac_phase_fault_clear_s', 0.0);
assignin(mw, 'hpt_sac_phase_recovery_end_s', 0.0);
assignin(mw, 'hpt_sac_vref_phase', 230.0);
assignin(mw, 'hpt_sac_grid_vref_phase', Vmv / sqrt(3));
assignin(mw, 'hpt_sac_vdc_ref', 800.0);
assignin(mw, 'hpt_sac_reg_max', 0.80);
assignin(mw, 'hpt_sac_energy_max', 0.95);
assignin(mw, 'hpt_sac_i_base_peak', sqrt(2) * Srated / (sqrt(3) * Vlv));
assignin(mw, 'hpt_sac_reg_polarity', 1.0);
assignin(mw, 'hpt_sac_reg_d_gain', 1.00);
assignin(mw, 'hpt_sac_reg_q_gain', 1.0);
assignin(mw, 'hpt_sac_dynamic_reg_limit', 0.60);
assignin(mw, 'hpt_sac_topology_id', 2.0);
assignin(mw, 'hpt_sac_fixed_reg_d', 0.0);
assignin(mw, 'hpt_sac_fixed_reg_q', 0.0);
assignin(mw, 'hpt_sac_fixed_energy_d', 0.0);
assignin(mw, 'hpt_sac_fixed_energy_q', 0.0);
assignin(mw, 'hpt_conventional_reg_scale', 1.0);
assignin(mw, 'hpt_conventional_energy_scale', 1.0);
assignin(mw, 'hpt_conventional_reg_scale_sag', 1.0);
assignin(mw, 'hpt_conventional_reg_scale_swell', 1.0);
assignin(mw, 'hpt_conventional_energy_scale_sag', 1.0);
assignin(mw, 'hpt_conventional_energy_scale_swell', 1.0);
assignin(mw, 'hpt_conventional_recovery_reg_gain', 0.0);
assignin(mw, 'hpt_conventional_recovery_reg_max', 0.0);
assignin(mw, 'hpt_conventional_recovery_hold_s', 0.0);
assignin(mw, 'hpt_sac_guard_enable', 0.0);
hpt_traj_t_default = (0:0.002:0.25)';
assignin(mw, 'hpt_traj_t', hpt_traj_t_default);
assignin(mw, 'hpt_traj_action', zeros(numel(hpt_traj_t_default), 4));

add_block('powerlib/powergui', [M '/powergui'], 'Position', P(20, 20, 70, 40));
set_param([M '/powergui'], 'SimulationMode', 'Discrete', 'SampleTime', num2str(Ts));

add_block('powerlib/Electrical Sources/Three-Phase Source', [M '/Grid'], ...
    'Position', P(60, 135, 60, 100));
set_param([M '/Grid'], 'Voltage', num2str(Vmv), 'Frequency', num2str(f0), ...
    'PhaseAngle', '0', 'InternalConnection', 'Yg', 'SpecifyImpedance', 'off');

add_block('powerlib/Elements/Three-Phase Series RLC Branch', [M '/Source_RL'], ...
    'Position', P(155, 145, 55, 80));
set_param([M '/Source_RL'], 'BranchType', 'RL', 'Resistance', num2str(Rg), ...
    'Inductance', num2str(Lg));

add_block('powerlib/Measurements/Three-Phase V-I Measurement', [M '/MeasPrimary'], ...
    'Position', P(245, 135, 70, 100));
set_param([M '/MeasPrimary'], 'VoltageMeasurement', 'phase-to-ground', ...
    'CurrentMeasurement', 'yes');

% Primary-side switch/link branches S1 and main transformer W1/W2.
for k = 1:3
    y = 80 + (k-1) * 115;
    sw = [M sprintf('/S1_link_%d', k)];
    add_block('powerlib/Elements/Series RLC Branch', sw, ...
        'Position', P(345, y+18, 55, 35));
    set_param(sw, 'BranchType', 'R', 'Resistance', '1e-3');

    tx = [M sprintf('/Main_W1W2_%d', k)];
    add_block('powerlib/Elements/Linear Transformer', tx, ...
        'Position', P(455, y, 95, 80));
    set_param(tx, 'ThreeWindings', 'off', ...
        'NominalPower', ['[' num2str(Srated/3) ',' num2str(f0) ']'], ...
        'winding1', ['[' num2str(Vmv/sqrt(3)) ',0.005,0.025]'], ...
        'winding2', ['[' num2str(Vlv/sqrt(3)) ',0.005,0.025]']);
end

% Secondary-side parallel coupled transformers.
for k = 1:3
    y = 80 + (k-1) * 115;
    pct = [M sprintf('/ParallelCoupled_%d', k)];
    add_block('powerlib/Elements/Linear Transformer', pct, ...
        'Position', P(720, y+8, 95, 72));
    set_param(pct, 'ThreeWindings', 'off', ...
        'NominalPower', ['[' num2str(Saux/3) ',' num2str(f0) ']'], ...
        'winding1', ['[' num2str(Vlv/sqrt(3)) ',0.004,0.02]'], ...
        'winding2', ['[' num2str(Vaux/sqrt(3)) ',0.004,0.02]']);
end

add_block('powerlib/Measurements/Three-Phase V-I Measurement', [M '/MeasLV'], ...
    'Position', P(980, 145, 70, 100));
set_param([M '/MeasLV'], 'VoltageMeasurement', 'phase-to-ground', ...
    'CurrentMeasurement', 'yes');

add_block('powerlib/Elements/Three-Phase Series RLC Load', [M '/Load'], ...
    'Position', P(1130, 155, 70, 80));
set_param([M '/Load'], 'NominalVoltage', num2str(Vlv), ...
    'NominalFrequency', num2str(f0), 'ActivePower', num2str(Srated), ...
    'InductivePower', '0', 'CapacitivePower', '0', ...
    'Configuration', 'Y (grounded)');

% TPFBVSC L filters and secondary-side switch/link branches S3.
for k = 1:3
    y = 455 + (k-1) * 55;
    add_block('powerlib/Elements/Series RLC Branch', [M sprintf('/TPF_L_%d', k)], ...
        'Position', P(830, y, 55, 35));
    set_param([M sprintf('/TPF_L_%d', k)], 'BranchType', 'L', ...
        'Inductance', num2str(Ltpf));

    add_block('powerlib/Elements/Series RLC Branch', [M sprintf('/S3_link_%d', k)], ...
        'Position', P(760, y, 45, 35));
    set_param([M sprintf('/S3_link_%d', k)], 'BranchType', 'R', 'Resistance', '1e-3');
end

add_block('powerlib/Measurements/Three-Phase V-I Measurement', [M '/MeasEnergy'], ...
    'Position', P(815, 455, 70, 95));
set_param([M '/MeasEnergy'], 'VoltageMeasurement', 'phase-to-ground', ...
    'CurrentMeasurement', 'yes');

add_voltage_regulator(M, 1220, 300);
add_energy_controller(M, 1220, 430);
add_hpt_sac_controller(M, 1220, 615);
add_regulating_converter_subsystem(M, 260, 760);
add_energy_converter_subsystem(M, 940, 430);

add_block('powerlib/Elements/Series RLC Branch', [M '/Cdc'], ...
    'Position', P(1210, 510, 40, 85));
set_param([M '/Cdc'], 'BranchType', 'C', 'Capacitance', num2str(Cdc), ...
    'Setx0', 'on', 'InitialVoltage', '800');

add_block('powerlib/Measurements/Voltage Measurement', [M '/MeasVdc'], ...
    'Position', P(1280, 505, 45, 45));
add_block('powerlib/Power Electronics/IGBT', [M '/Chopper'], ...
    'Position', P(1370, 505, 40, 55));
add_block('powerlib/Elements/Series RLC Branch', [M '/Rchop'], ...
    'Position', P(1370, 590, 45, 55));
set_param([M '/Rchop'], 'BranchType', 'R', 'Resistance', 'hpt_rchop');
add_block('simulink/Sources/Constant', [M '/Chopper_gate'], ...
    'Position', P(1295, 615, 55, 25), 'Value', 'hpt_chopper_threshold');
add_block('simulink/Logic and Bit Operations/Relational Operator', [M '/Chopper_cmp'], ...
    'Position', P(1340, 540, 40, 35));
set_param([M '/Chopper_cmp'], 'Operator', '>');
add_block('simulink/Sources/Constant', [M '/SAC_enable'], ...
    'Position', P(1320, 370, 55, 25), 'Value', 'hpt_sac_enable');
add_block('simulink/Sources/Constant', [M '/SAC_energy_enable'], ...
    'Position', P(1320, 480, 55, 25), 'Value', 'hpt_sac_energy_enable');
add_block('simulink/Signal Routing/Switch', [M '/RegCommandSelect'], ...
    'Position', P(1400, 315, 50, 50));
set_param([M '/RegCommandSelect'], 'Criteria', 'u2 >= Threshold', 'Threshold', '0.5');
add_block('simulink/Signal Routing/Switch', [M '/EnergyCommandSelect'], ...
    'Position', P(1400, 425, 50, 50));
set_param([M '/EnergyCommandSelect'], 'Criteria', 'u2 >= Threshold', 'Threshold', '0.5');

% Ground references.
add_ground(M, 'W1_neutral_ground', P(420, 430, 25, 25));
add_ground(M, 'W2_neutral_ground', P(600, 430, 25, 25));
add_ground(M, 'PCT_primary_neutral_ground', P(680, 430, 25, 25));
add_ground(M, 'PCT_secondary_neutral_ground', P(780, 650, 25, 25));
add_ground(M, 'HBC_return_ground', P(245, 950, 25, 25));

% Logging.
add_block('simulink/Sinks/To Workspace', [M '/Vpri_abc'], ...
    'Position', P(1180, 105, 85, 25), 'VariableName', 'Vpri_abc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Igrid_abc'], ...
    'Position', P(1180, 185, 85, 25), 'VariableName', 'Igrid_abc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Vlv_abc'], ...
    'Position', P(1180, 145, 85, 25), 'VariableName', 'Vlv_abc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Vdc'], ...
    'Position', P(1340, 505, 70, 25), 'VariableName', 'Vdc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Mreg_cmd'], ...
    'Position', P(1325, 300, 80, 25), 'VariableName', 'Mreg_cmd', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Mref6_cmd'], ...
    'Position', P(1325, 335, 80, 25), 'VariableName', 'Mref6_cmd', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Menergy_cmd'], ...
    'Position', P(1325, 430, 90, 25), 'VariableName', 'Menergy_cmd', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Energy_Vabc'], ...
    'Position', P(1180, 430, 90, 25), 'VariableName', 'Energy_Vabc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Energy_Iabc'], ...
    'Position', P(1180, 460, 90, 25), 'VariableName', 'Energy_Iabc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Energy_dbg'], ...
    'Position', P(1325, 460, 90, 25), 'VariableName', 'Energy_dbg', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/HPTSAC_obs'], ...
    'Position', P(1325, 615, 90, 25), 'VariableName', 'HPTSAC_obs', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/HPTSAC_action'], ...
    'Position', P(1325, 645, 90, 25), 'VariableName', 'HPTSAC_action', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Signal Routing/Mux', [M '/Reg_Iabc_mux'], ...
    'Position', P(1110, 675, 10, 75), 'Inputs', '3');
add_block('simulink/Sinks/To Workspace', [M '/Reg_Iabc'], ...
    'Position', P(1180, 700, 90, 25), 'VariableName', 'Reg_Iabc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Signal Routing/Mux', [M '/HBC_Cap_Vabc_mux'], ...
    'Position', P(1110, 755, 10, 75), 'Inputs', '3');
add_block('simulink/Sinks/To Workspace', [M '/HBC_Cap_Vabc'], ...
    'Position', P(1180, 780, 110, 25), 'VariableName', 'HBC_Cap_Vabc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Signal Routing/Mux', [M '/Series_W5_Vabc_mux'], ...
    'Position', P(1110, 835, 10, 75), 'Inputs', '3');
add_block('simulink/Sinks/To Workspace', [M '/Series_W5_Vabc'], ...
    'Position', P(1180, 860, 110, 25), 'VariableName', 'Series_W5_Vabc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Signal Routing/Mux', [M '/Series_W6_Vabc_mux'], ...
    'Position', P(1110, 915, 10, 75), 'Inputs', '3');
add_block('simulink/Sinks/To Workspace', [M '/Series_W6_Vabc'], ...
    'Position', P(1180, 940, 110, 25), 'VariableName', 'Series_W6_Vabc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Signal Routing/Mux', [M '/Vinj_abc_mux'], ...
    'Position', P(1110, 995, 10, 75), 'Inputs', '3');
add_block('simulink/Sinks/To Workspace', [M '/Vinj_abc'], ...
    'Position', P(1180, 1020, 90, 25), 'VariableName', 'Vinj_abc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Discrete/Unit Delay', [M '/Vdc_delay_for_Idc'], ...
    'Position', P(1420, 650, 45, 25), 'SampleTime', num2str(Ts), ...
    'InitialCondition', '800');
add_block('simulink/Math Operations/Sum', [M '/Vdc_delta_for_Idc'], ...
    'Position', P(1490, 640, 35, 35), 'Inputs', '+-');
add_block('simulink/Math Operations/Gain', [M '/Cdc_dvdt_gain'], ...
    'Position', P(1555, 645, 60, 25), 'Gain', sprintf('%.12g', Cdc / Ts));
add_block('simulink/Sinks/To Workspace', [M '/Idc_cap'], ...
    'Position', P(1645, 645, 80, 25), 'VariableName', 'Idc_cap', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
% Switch-level regulating injection path. W6 is inserted in the main load
% path; W5 is driven by the HBC through the per-phase LC filter.
for k = 1:3
    y = 650 + (k-1) * 65;
    add_block('powerlib/Measurements/Current Measurement', ...
        [M sprintf('/Reg_I_%d', k)], 'Position', P(635, y, 35, 30));
    add_block('powerlib/Elements/Series RLC Branch', [M sprintf('/SwHBC_L_%d', k)], ...
        'Position', P(700, y, 55, 30));
    set_param([M sprintf('/SwHBC_L_%d', k)], 'BranchType', 'RL', ...
        'Resistance', num2str(Rhbc), 'Inductance', num2str(Lhbc));

    add_block('powerlib/Measurements/Voltage Measurement', ...
        [M sprintf('/HBC_Cap_V_%d', k)], 'Position', P(865, y+35, 35, 25));
    add_block('powerlib/Elements/Series RLC Branch', [M sprintf('/SwHBC_C_%d', k)], ...
        'Position', P(805, y+35, 45, 30));
    set_param([M sprintf('/SwHBC_C_%d', k)], 'BranchType', 'C', ...
        'Capacitance', num2str(Chbc), 'Setx0', 'off');

    blk = [M sprintf('/SwRegSeries_W5W6_%d', k)];
    add_block('powerlib/Elements/Linear Transformer', blk, ...
        'Position', P(880, y-10, 85, 65));
    set_param(blk, 'ThreeWindings', 'off', ...
        'NominalPower', ['[' num2str(Sser) ',' num2str(f0) ']'], ...
        'winding1', ['[' num2str(Vw5) ',0.002,0.03]'], ...
        'winding2', ['[' num2str(Vw6) ',0.002,0.03]']);

end
for k = 1:3
    add_block('powerlib/Measurements/Voltage Measurement', ...
        [M sprintf('/SwW5_V_%d', k)], 'Position', P(1035, 640 + (k-1)*28, 35, 25));
    add_block('powerlib/Measurements/Voltage Measurement', ...
        [M sprintf('/SwW6_V_%d', k)], 'Position', P(1035, 735 + (k-1)*28, 35, 25));
end

% Main electrical path.
for k = 1:3
    add_line(M, ph([M '/Grid'], 'RConn', k), ph([M '/Source_RL'], 'LConn', k), ...
        'autorouting', 'on');
    add_line(M, ph([M '/Source_RL'], 'RConn', k), ph([M '/MeasPrimary'], 'LConn', k), ...
        'autorouting', 'on');
    add_line(M, ph([M '/MeasPrimary'], 'RConn', k), ...
        ph([M sprintf('/S1_link_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/S1_link_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/Main_W1W2_%d', k)], 'LConn', 1), 'autorouting', 'on');

    add_line(M, ph([M sprintf('/Main_W1W2_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/ParallelCoupled_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/Main_W1W2_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/SwRegSeries_W5W6_%d', k)], 'RConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/SwRegSeries_W5W6_%d', k)], 'RConn', 2), ...
        ph([M '/MeasLV'], 'LConn', k), 'autorouting', 'on');
    add_line(M, ph([M '/MeasLV'], 'RConn', k), ph([M '/Load'], 'LConn', k), ...
        'autorouting', 'on');

    % Parallel coupled transformer secondary -> S3/L filter -> TPFBVSC.
    add_line(M, ph([M sprintf('/ParallelCoupled_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/S3_link_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/S3_link_%d', k)], 'RConn', 1), ...
        ph([M '/MeasEnergy'], 'LConn', k), 'autorouting', 'on');
    add_line(M, ph([M '/MeasEnergy'], 'RConn', k), ...
        ph([M sprintf('/TPF_L_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/TPF_L_%d', k)], 'RConn', 1), ...
        ph([M '/EnergyConverter'], 'LConn', k), 'autorouting', 'on');

    % Reintroduced switch-level regulating path for staged calibration.
    add_line(M, ph([M '/RegulatingConverter'], 'LConn', 2*k-1), ...
        ph([M sprintf('/Reg_I_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/Reg_I_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/SwHBC_L_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/SwHBC_L_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/SwRegSeries_W5W6_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M '/RegulatingConverter'], 'LConn', 2*k), ...
        ph([M sprintf('/SwRegSeries_W5W6_%d', k)], 'LConn', 2), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/SwHBC_L_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/SwHBC_C_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/SwHBC_C_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/SwRegSeries_W5W6_%d', k)], 'LConn', 2), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/HBC_Cap_V_%d', k)], 'LConn', 1), ...
        ph([M sprintf('/SwHBC_C_%d', k)], 'LConn', 1), 'autorouting', 'on');
