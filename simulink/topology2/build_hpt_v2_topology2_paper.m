function create_named_subsystem(M, subsystemName, blockNames)
before = find_system(M, 'SearchDepth', 1, 'BlockType', 'SubSystem');
beforeHandles = cellfun(@(b) get_param(b, 'Handle'), before);
handles = zeros(1, numel(blockNames));
for i = 1:numel(blockNames)
    blockPath = [M '/' blockNames{i}];
    assert(getSimulinkBlockHandle(blockPath) > 0, ...
        'Missing block for %s subsystem: %s', subsystemName, blockPath);
    handles(i) = get_param(blockPath, 'Handle');
end
Simulink.BlockDiagram.createSubsystem(handles);
after = find_system(M, 'SearchDepth', 1, 'BlockType', 'SubSystem');
afterHandles = cellfun(@(b) get_param(b, 'Handle'), after);
newHandles = setdiff(afterHandles, beforeHandles);
assert(numel(newHandles) == 1, ...
    'Expected one new subsystem for %s, found %d', subsystemName, numel(newHandles));
set_param(newHandles(1), 'Name', subsystemName, 'ShowName', 'on');
end

