after = find_system(M, 'SearchDepth', 1, 'BlockType', 'SubSystem');
afterHandles = cellfun(@(b) get_param(b, 'Handle'), after);
newHandles = setdiff(afterHandles, beforeHandles);
assert(numel(newHandles) == 1, ...
    'Expected one new subsystem for %s, found %d', subsystemName, numel(newHandles));
set_param(newHandles(1), 'Name', subsystemName, 'ShowName', 'on');
end

