function codeText = pll_dq_controller_code()
codeText = strjoin({ ...
    ['function [m_ref6, ctrl_dbg] = fcn(Vabc, ts, grid_f0, vref_lv, ', ...
    'vreg_kp, vreg_ki, m_max, pll_kp, pll_ki, inj_phase, swell_gain)'], ...
    '%#codegen', ...
    'persistent theta xi_pll xi_a xi_b xi_c t_ctrl v_rms_f', ...
    'if isempty(theta)', ...
    '    theta = 0;', ...
    '    xi_pll = 0;', ...
    '    xi_a = 0;', ...
    '    xi_b = 0;', ...
    '    xi_c = 0;', ...
    '    t_ctrl = 0;', ...
    '    v_rms_f = 0;', ...
    'end', ...
    't_ctrl = t_ctrl + ts;', ...
    'm_ref6 = zeros(6, 1);', ...
    'ctrl_dbg = zeros(7, 1);', ...
    'va = Vabc(1);', ...
    'vb = Vabc(2);', ...
    'vc = Vabc(3);', ...
    'alpha = (2/3) * (va - 0.5*vb - 0.5*vc);', ...
    'beta = (sqrt(3)/3) * (vb - vc);', ...
    'theta_meas = atan2(beta, alpha);', ...
    'pll_err = atan2(sin(theta_meas - theta), cos(theta_meas - theta));', ...
    'xi_pll = xi_pll + pll_ki * pll_err * ts;', ...
    'omega = 2*pi*grid_f0 + pll_kp * pll_err + xi_pll;', ...
    'theta = theta + omega * ts;', ...
    'theta = theta - 2*pi*floor(theta/(2*pi));', ...
    'ct = cos(theta);', ...
    'st = sin(theta);', ...
    'vd = alpha*ct + beta*st;', ...
    'vq = -alpha*st + beta*ct;', ...
    'v_rms = sqrt(max((va*va + vb*vb + vc*vc) / 3, 0));', ...
    'if v_rms_f == 0', ...
    '    v_rms_f = v_rms;', ...
    'end', ...
    'alpha_v = min(max(ts / 0.005, 0), 1);', ...
    'v_rms_f = v_rms_f + alpha_v * (v_rms - v_rms_f);', ...
    'v_meas = v_rms_f;', ...
    'v_err = vref_lv - v_meas;', ...
    'err_pu = v_err / max(vref_lv, 1e-6);', ...
    'phi = inj_phase;', ...
    'if abs(err_pu) < 0.002', ...
    '    kp_eff = 0;', ...
    '    ki_eff = 0;', ...
    '    xi_a = 0;', ...
    '    xi_b = 0;', ...
    '    xi_c = 0;', ...
    '    err_eff = 0;', ...
    'elseif err_pu >= 0', ...
    '    kp_eff = abs(vreg_kp);', ...
    '    ki_eff = abs(vreg_ki);', ...
    '    err_eff = err_pu;', ...
    'else', ...
    '    kp_eff = abs(vreg_kp) * swell_gain;', ...
    '    ki_eff = abs(vreg_ki) * swell_gain;', ...
    '    err_eff = err_pu;', ...
    '    if kp_eff == 0 && ki_eff == 0', ...
    '        xi_a = 0;', ...
    '        xi_b = 0;', ...
    '        xi_c = 0;', ...
    '    end', ...
    'end', ...
    'if t_ctrl > 0.02', ...
    '    xi_a = xi_a + ki_eff * err_eff * ts;', ...
    'else', ...
    '    xi_a = 0;', ...
    'end', ...
    'm_unsat = kp_eff * err_eff + xi_a;', ...
    'm_cmd = min(max(m_unsat, -m_max), m_max);', ...
    'if m_cmd ~= m_unsat', ...
    '    xi_a = m_cmd - kp_eff * err_eff;', ...
    'end', ...
    'ma = m_cmd * sin(theta + phi);', ...
    'mb = m_cmd * sin(theta + phi - 2*pi/3);', ...
    'mc = m_cmd * sin(theta + phi + 2*pi/3);', ...
    'm_amp = sqrt((ma*ma + mb*mb + mc*mc) / 3);', ...
    'm_ref6 = [ma; -ma; mb; -mb; mc; -mc];', ...
    'ctrl_dbg = [theta; vd; vq; v_meas; v_err; m_amp; phi];', ...
    'end' ...
    }, newline);
end

function codeText = energy_controller_code()
codeText = strjoin({ ...
    ['function [m_abc, dbg] = fcn(vdc, Vabc, Iabc, ts, grid_f0, vdc_ref, ', ...
    'vdc_kp, vdc_ki, id_max, cur_kp, cur_ki, mmax, pll_kp, pll_ki, ', ...
    'vff_gain, control_sign, polarity, open_amp, open_phase)'], ...
    '%#codegen', ...
    'persistent theta xi_pll xi_vdc xi_id xi_iq t_ctrl', ...
    'if isempty(theta)', ...
    '    theta = 0;', ...
    '    xi_pll = 0;', ...
    '    xi_vdc = 0;', ...
    '    xi_id = 0;', ...
    '    xi_iq = 0;', ...
    '    t_ctrl = 0;', ...
    'end', ...
    't_ctrl = t_ctrl + ts;', ...
    'va = Vabc(1); vb = Vabc(2); vc = Vabc(3);', ...
    'ia = Iabc(1); ib = Iabc(2); ic = Iabc(3);', ...
    'valpha = (2/3) * (va - 0.5*vb - 0.5*vc);', ...
    'vbeta = (sqrt(3)/3) * (vb - vc);', ...
    'ialpha = (2/3) * (ia - 0.5*ib - 0.5*ic);', ...
    'ibeta = (sqrt(3)/3) * (ib - ic);', ...
    'theta_meas = atan2(vbeta, valpha);', ...
    'pll_err = atan2(sin(theta_meas - theta), cos(theta_meas - theta));', ...
    'xi_pll = xi_pll + pll_ki * pll_err * ts;', ...
    'omega = 2*pi*grid_f0 + pll_kp * pll_err + xi_pll;', ...
    'theta = theta + omega * ts;', ...
    'theta = theta - 2*pi*floor(theta/(2*pi));', ...
    'ct = cos(theta); st = sin(theta);', ...
    'if open_amp > 0', ...
    '    mo = min(open_amp, mmax);', ...
    '    ma = mo * sin(theta + open_phase);', ...
    '    mb = mo * sin(theta + open_phase - 2*pi/3);', ...
    '    mc = mo * sin(theta + open_phase + 2*pi/3);', ...
    '    p_ac = va*ia + vb*ib + vc*ic;', ...
    '    m_abc = polarity * [ma; mb; mc];', ...
    '    dbg = [theta; 0; 0; 0; 0; 0; vdc; vdc_ref-vdc; p_ac; ma; mb; mc];', ...
    '    return;', ...
    'end', ...
    'vd = valpha*ct + vbeta*st;', ...
    'vq = -valpha*st + vbeta*ct;', ...
    'id = ialpha*ct + ibeta*st;', ...
    'iq = -ialpha*st + ibeta*ct;', ...
    'err = vdc_ref - vdc;', ...
    'if abs(err) < 3 || t_ctrl < 0.02', ...
    '    xi_vdc = 0;', ...
    '    id_ref = 0;', ...
    'else', ...
    '    xi_vdc = xi_vdc + vdc_ki * err * ts;', ...
    '    id_unsat = vdc_kp * err + xi_vdc;', ...
    '    id_ref = min(max(id_unsat, -id_max), id_max);', ...
    '    if id_ref ~= id_unsat', ...
    '        xi_vdc = id_ref - vdc_kp * err;', ...
    '    end', ...
    'end', ...
    'iq_ref = 0;', ...
    'eid = id_ref - id;', ...
    'eiq = iq_ref - iq;', ...
    'xi_id = xi_id + cur_ki * eid * ts;', ...
    'xi_iq = xi_iq + cur_ki * eiq * ts;', ...
    'vd_ctrl = cur_kp * eid + xi_id;', ...
    'vq_ctrl = cur_kp * eiq + xi_iq;', ...
    'vconv_d = vff_gain * vd - control_sign * vd_ctrl;', ...
    'vconv_q = vff_gain * vq - control_sign * vq_ctrl;', ...
    'conv_alpha = vconv_d*ct - vconv_q*st;', ...
    'conv_beta = vconv_d*st + vconv_q*ct;', ...
    'ma_unsat = 2 * conv_alpha / max(abs(vdc), 50);', ...
    'mb_unsat = 2 * (-0.5*conv_alpha + (sqrt(3)/2)*conv_beta) / max(abs(vdc), 50);', ...
    'mc_unsat = 2 * (-0.5*conv_alpha - (sqrt(3)/2)*conv_beta) / max(abs(vdc), 50);', ...
    'ma = min(max(ma_unsat, -mmax), mmax);', ...
    'mb = min(max(mb_unsat, -mmax), mmax);', ...
    'mc = min(max(mc_unsat, -mmax), mmax);', ...
    'if abs(ma) >= mmax || abs(mb) >= mmax || abs(mc) >= mmax', ...
    '    xi_id = xi_id - cur_ki * eid * ts;', ...
    '    xi_iq = xi_iq - cur_ki * eiq * ts;', ...
    'end', ...
    'm_abc = polarity * [ma; mb; mc];', ...
    'p_ac = va*ia + vb*ib + vc*ic;', ...
    'dbg = [theta; vd; vq; id; iq; id_ref; vdc; err; p_ac; ma; mb; mc];', ...
    'end' ...
    }, newline);
end

