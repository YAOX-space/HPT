    blockPath = [M '/' blockNames{i}];
    assert(getSimulinkBlockHandle(blockPath) > 0, ...
        'Missing block for %s subsystem: %s', subsystemName, blockPath);
    handles(i) = get_param(blockPath, 'Handle');
