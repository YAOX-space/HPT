function build_hpt_v2_1to1_switchlevel()
% build_hpt_v2_1to1_switchlevel
% Reference-structure HPT topology model.
%
% The model follows the supplied topology diagram:
%   - Main transformer: W1/W2 per phase.
%   - New flexible distribution transformer: W3/W4 per phase.
%   - Energy converter: fed from W4 through an RL filter.
%   - Regulating converter: drives W5 of the series transformers.
%   - Series injection transformers: W6 is inserted in each load phase.
%   - Energy and regulating converters share the DC link.
%
% This is a switch-level topology skeleton.  Each converter leg is built from
% individual IGBT blocks.  Converter gates are held off by default; control/PWM
% migration and parameter calibration should be done in a later step.

M = 'hpt_v2_1to1_switchlevel';
if bdIsLoaded(M)
    set_param(M, 'Dirty', 'off');
    close_system(M, 0);
end
new_system(M);
load_system(M);
thisDir = fileparts(mfilename('fullpath'));
addpath(thisDir);
addpath(fileparts(thisDir));

f0 = 50;
Ts = 20e-6;
Vmv = 10e3;
Vlv = 400;
Srated = 400e3;
Saux = 120e3;
Sser = 30e3;
Vaux = 400;
Vw5 = 400;
Vw6 = 100;
Rtake = 0.05;
Ltake = 3e-3;
Cdc = 2200e-6;
Rchop = (800^2) / Saux;

Zb = Vmv^2 / Srated;
scr = 3;
Zg = Zb / scr;
Rg = Zg / sqrt(1 + 49);
Lg = 7 * Rg / (2 * pi * f0);

P = @(x, y, w, h) [x y x+w y+h];
set_param(M, 'Solver', 'ode23tb', 'StopTime', '0.2');
mw = get_param(M, 'ModelWorkspace');
assignin(mw, 'hpt_pwm_fs', 2000);
assignin(mw, 'hpt_m_energy', 0.00);
assignin(mw, 'hpt_m_reg', 0.10);
assignin(mw, 'hpt_ctrl_Ts', Ts);
assignin(mw, 'hpt_grid_f0', f0);
assignin(mw, 'hpt_vdc_ref', 800.0);
assignin(mw, 'hpt_rchop', Rchop);
assignin(mw, 'hpt_chopper_threshold', 850.0);
assignin(mw, 'hpt_vdc_kp', 0.10);
assignin(mw, 'hpt_vdc_ki', 0.20);
assignin(mw, 'hpt_energy_id_max', 20.0);
assignin(mw, 'hpt_energy_i_kp', 0.50);
assignin(mw, 'hpt_energy_i_ki', 100.0);
assignin(mw, 'hpt_m_energy_max', 0.95);
assignin(mw, 'hpt_energy_vff_gain', 1.06);
assignin(mw, 'hpt_energy_control_sign', -1.0);
assignin(mw, 'hpt_energy_bridge_polarity', -1.0);
assignin(mw, 'hpt_energy_openloop_amp', 0.0);
assignin(mw, 'hpt_energy_openloop_phase', 0.0);
assignin(mw, 'hpt_vref_lv', 207.0);
assignin(mw, 'hpt_vreg_kp', 20.0);
assignin(mw, 'hpt_vreg_ki', 0.0);
assignin(mw, 'hpt_m_reg_max', 0.80);
assignin(mw, 'hpt_pll_kp', 80.0);
assignin(mw, 'hpt_pll_ki', 2500.0);
assignin(mw, 'hpt_inj_phase_offset', -1.05);
assignin(mw, 'hpt_swell_gain_scale', 1.0);
assignin(mw, 'hpt_sac_enable', 0.0);
assignin(mw, 'hpt_sac_energy_enable', 0.0);
assignin(mw, 'hpt_sac_policy_mode', 0.0);
assignin(mw, 'hpt_sac_actor_select_mode', 0.0);
assignin(mw, 'hpt_sac_actor_filter_tau', 0.001);
assignin(mw, 'hpt_sac_gridnorm_startup_s', 0.030);
assignin(mw, 'hpt_sac_fault_time_norm_s', 0.50);
assignin(mw, 'hpt_sac_recovery_time_norm_s', 0.50);
assignin(mw, 'hpt_sac_phase_override_enable', 0.0);
assignin(mw, 'hpt_sac_phase_fault_start_s', 0.0);
assignin(mw, 'hpt_sac_phase_fault_clear_s', 0.0);
assignin(mw, 'hpt_sac_phase_recovery_end_s', 0.0);
assignin(mw, 'hpt_sac_vref_phase', 230.0);
assignin(mw, 'hpt_sac_grid_vref_phase', Vmv / sqrt(3));
assignin(mw, 'hpt_sac_vdc_ref', 800.0);
assignin(mw, 'hpt_sac_reg_max', 0.80);
assignin(mw, 'hpt_sac_energy_max', 0.95);
assignin(mw, 'hpt_sac_i_base_peak', sqrt(2) * Srated / (sqrt(3) * Vlv));
assignin(mw, 'hpt_sac_reg_polarity', 1.0);
assignin(mw, 'hpt_sac_reg_d_gain', 1.00);
assignin(mw, 'hpt_sac_reg_q_gain', 1.0);
assignin(mw, 'hpt_sac_dynamic_reg_limit', 0.80);
assignin(mw, 'hpt_sac_topology_id', 1.0);
assignin(mw, 'hpt_sac_fixed_reg_d', 0.0);
assignin(mw, 'hpt_sac_fixed_reg_q', 0.0);
assignin(mw, 'hpt_sac_fixed_energy_d', 0.0);
assignin(mw, 'hpt_sac_fixed_energy_q', 0.0);
assignin(mw, 'hpt_conventional_reg_scale', 1.0);
assignin(mw, 'hpt_conventional_energy_scale', 1.0);
assignin(mw, 'hpt_conventional_reg_scale_sag', 1.0);
assignin(mw, 'hpt_conventional_reg_scale_swell', 1.0);
assignin(mw, 'hpt_conventional_energy_scale_sag', 1.0);
assignin(mw, 'hpt_conventional_energy_scale_swell', 1.0);
assignin(mw, 'hpt_conventional_recovery_reg_gain', 0.0);
assignin(mw, 'hpt_conventional_recovery_reg_max', 0.0);
assignin(mw, 'hpt_conventional_recovery_hold_s', 0.0);
assignin(mw, 'hpt_sac_guard_enable', 0.0);
hpt_traj_t_default = (0:0.002:0.25)';
assignin(mw, 'hpt_traj_t', hpt_traj_t_default);
assignin(mw, 'hpt_traj_action', zeros(numel(hpt_traj_t_default), 4));

add_block('powerlib/powergui', [M '/powergui'], 'Position', P(20, 20, 70, 40));
set_param([M '/powergui'], 'SimulationMode', 'Discrete', 'SampleTime', num2str(Ts));

% Grid and weak-grid impedance.
add_block('powerlib/Electrical Sources/Three-Phase Source', [M '/Grid'], ...
    'Position', P(60, 115, 60, 90));
set_param([M '/Grid'], 'Voltage', num2str(Vmv), 'Frequency', num2str(f0), ...
    'PhaseAngle', '0', 'InternalConnection', 'Yg', ...
    'SpecifyImpedance', 'off', 'Resistance', '1e-3', 'Inductance', '1e-5');

add_block('powerlib/Elements/Three-Phase Series RLC Branch', [M '/Zg'], ...
    'Position', P(155, 120, 55, 70));
set_param([M '/Zg'], 'BranchType', 'RL', 'Resistance', num2str(Rg), ...
    'Inductance', num2str(Lg));

add_block('powerlib/Measurements/Three-Phase V-I Measurement', [M '/MeasMV'], ...
    'Position', P(245, 115, 70, 90));
set_param([M '/MeasMV'], 'VoltageMeasurement', 'phase-to-ground', ...
    'CurrentMeasurement', 'yes');

% Main transformer W1/W2.
for k = 1:3
    y = 70 + (k-1) * 115;
    blk = [M sprintf('/Main_W1W2_%d', k)];
    add_block('powerlib/Elements/Linear Transformer', blk, ...
        'Position', P(375, y, 95, 78));
    set_param(blk, 'ThreeWindings', 'off', ...
        'NominalPower', ['[' num2str(Srated/3) ',' num2str(f0) ']'], ...
        'winding1', ['[' num2str(Vmv/sqrt(3)) ',0.005,0.025]'], ...
        'winding2', ['[' num2str(Vlv/sqrt(3)) ',0.005,0.025]']);
end

% Primary-side energy coupling transformer W3/W4.
for k = 1:3
    x = 300 + (k-1) * 125;
    blk = [M sprintf('/Flex_W3W4_%d', k)];
    add_block('powerlib/Elements/Linear Transformer', blk, ...
        'Position', P(x, 430, 82, 78));
    set_param(blk, 'ThreeWindings', 'off', ...
        'NominalPower', ['[' num2str(Saux/3) ',' num2str(f0) ']'], ...
        'winding1', ['[' num2str(Vmv/sqrt(3)) ',0.005,0.02]'], ...
        'winding2', ['[' num2str(Vaux/sqrt(3)) ',0.005,0.02]']);
end

% Series injection transformer W5/W6.  W6 is in the load path; W5 is fed by
% the regulating converter.
for k = 1:3
    y = 70 + (k-1) * 115;
    blk = [M sprintf('/Series_W5W6_%d', k)];
    add_block('powerlib/Elements/Linear Transformer', blk, ...
        'Position', P(650, y, 95, 72));
    set_param(blk, 'ThreeWindings', 'off', ...
        'NominalPower', ['[' num2str(Sser) ',' num2str(f0) ']'], ...
        'winding1', ['[' num2str(Vw5) ',0.002,0.03]'], ...
        'winding2', ['[' num2str(Vw6) ',0.002,0.03]']);
end

add_block('powerlib/Measurements/Three-Phase V-I Measurement', [M '/MeasLV'], ...
    'Position', P(805, 135, 70, 100));
set_param([M '/MeasLV'], 'VoltageMeasurement', 'phase-to-ground', ...
    'CurrentMeasurement', 'no');

add_block('powerlib/Elements/Three-Phase Series RLC Load', [M '/Load'], ...
    'Position', P(950, 150, 70, 80));
set_param([M '/Load'], 'NominalVoltage', num2str(Vlv), ...
    'NominalFrequency', num2str(f0), 'ActivePower', num2str(Srated), ...
    'InductivePower', '0', 'CapacitivePower', '0', ...
    'Configuration', 'Y (grounded)');

% Energy converter chain: W4 -> measurement -> RL filter -> ShVSC.
add_block('powerlib/Measurements/Three-Phase V-I Measurement', [M '/MeasEnergy'], ...
    'Position', P(690, 455, 70, 95));
set_param([M '/MeasEnergy'], 'VoltageMeasurement', 'phase-to-ground', ...
    'CurrentMeasurement', 'yes');

add_block('powerlib/Elements/Three-Phase Series RLC Branch', [M '/Energy_RL'], ...
    'Position', P(800, 470, 60, 65));
set_param([M '/Energy_RL'], 'BranchType', 'RL', 'Resistance', num2str(Rtake), ...
    'Inductance', num2str(Ltake));

add_voltage_regulator(M, 1010, 260);
add_energy_controller(M, 1010, 395);
add_hpt_sac_controller(M, 1010, 570);
add_energy_converter_subsystem(M, 910, 430);
add_regulating_converter_subsystem(M, 250, 665);

add_block('powerlib/Elements/Series RLC Branch', [M '/Cdc'], ...
    'Position', P(1160, 470, 40, 85));
set_param([M '/Cdc'], 'BranchType', 'C', 'Capacitance', num2str(Cdc), ...
    'Setx0', 'on', 'InitialVoltage', '800');

add_block('powerlib/Measurements/Voltage Measurement', [M '/MeasVdc'], ...
    'Position', P(1230, 465, 45, 45));

add_block('powerlib/Power Electronics/IGBT', [M '/Chop'], ...
    'Position', P(1325, 465, 40, 55));
add_block('powerlib/Elements/Series RLC Branch', [M '/Rchop'], ...
    'Position', P(1325, 550, 45, 55));
set_param([M '/Rchop'], 'BranchType', 'R', 'Resistance', 'hpt_rchop');

% Ground references for the single-phase winding groups.
add_block('powerlib/Elements/Ground', [M '/W1_neutral_ground'], ...
    'Position', P(325, 395, 25, 25));
add_block('powerlib/Elements/Ground', [M '/W2_neutral_ground'], ...
    'Position', P(545, 395, 25, 25));
add_block('powerlib/Elements/Ground', [M '/W3_neutral_ground'], ...
    'Position', P(265, 555, 25, 25));
add_block('powerlib/Elements/Ground', [M '/W4_neutral_ground'], ...
    'Position', P(645, 555, 25, 25));

% DC-link overvoltage chopper gate.
add_block('simulink/Sources/Constant', [M '/Chop_gate'], ...
    'Position', P(1215, 575, 60, 25), 'Value', 'hpt_chopper_threshold');
add_block('simulink/Logic and Bit Operations/Relational Operator', [M '/Chop_cmp'], ...
    'Position', P(1290, 545, 40, 35));
set_param([M '/Chop_cmp'], 'Operator', '>');
add_block('simulink/Sources/Constant', [M '/SAC_enable'], ...
    'Position', P(1205, 355, 55, 25), 'Value', 'hpt_sac_enable');
add_block('simulink/Sources/Constant', [M '/SAC_energy_enable'], ...
    'Position', P(1205, 455, 55, 25), 'Value', 'hpt_sac_energy_enable');
add_block('simulink/Signal Routing/Switch', [M '/RegCommandSelect'], ...
    'Position', P(1280, 300, 50, 50));
set_param([M '/RegCommandSelect'], 'Criteria', 'u2 >= Threshold', 'Threshold', '0.5');
add_block('simulink/Signal Routing/Switch', [M '/EnergyCommandSelect'], ...
    'Position', P(1280, 405, 50, 50));
set_param([M '/EnergyCommandSelect'], 'Criteria', 'u2 >= Threshold', 'Threshold', '0.5');

% Logging.
add_block('simulink/Sinks/To Workspace', [M '/Vmv_abc'], ...
    'Position', P(1125, 115, 85, 25), 'VariableName', 'Vmv_abc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Igrid_abc'], ...
    'Position', P(1125, 185, 85, 25), 'VariableName', 'Igrid_abc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Vlv_abc'], ...
    'Position', P(1125, 150, 85, 25), 'VariableName', 'Vlv_abc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Vdc'], ...
    'Position', P(1290, 465, 70, 25), 'VariableName', 'Vdc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Mreg_cmd'], ...
    'Position', P(1210, 270, 80, 25), 'VariableName', 'Mreg_cmd', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Mref6_cmd'], ...
    'Position', P(1210, 305, 80, 25), 'VariableName', 'Mref6_cmd', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Menergy_cmd'], ...
    'Position', P(1210, 395, 90, 25), 'VariableName', 'Menergy_cmd', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Energy_Vabc'], ...
    'Position', P(1125, 425, 90, 25), 'VariableName', 'Energy_Vabc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Energy_Iabc'], ...
    'Position', P(1125, 455, 90, 25), 'VariableName', 'Energy_Iabc', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/Energy_dbg'], ...
    'Position', P(1210, 425, 90, 25), 'VariableName', 'Energy_dbg', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/HPTSAC_obs'], ...
    'Position', P(1210, 570, 90, 25), 'VariableName', 'HPTSAC_obs', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));
add_block('simulink/Sinks/To Workspace', [M '/HPTSAC_action'], ...
    'Position', P(1210, 600, 90, 25), 'VariableName', 'HPTSAC_action', ...
    'SaveFormat', 'Array', 'SampleTime', num2str(Ts));

% Main power path and transformer taps.
for k = 1:3
    add_line(M, ph([M '/Grid'], 'RConn', k), ph([M '/Zg'], 'LConn', k), ...
        'autorouting', 'on');
    add_line(M, ph([M '/Zg'], 'RConn', k), ph([M '/MeasMV'], 'LConn', k), ...
        'autorouting', 'on');
    add_line(M, ph([M '/MeasMV'], 'RConn', k), ...
        ph([M sprintf('/Main_W1W2_%d', k)], 'LConn', 1), 'autorouting', 'on');

    % W2 phase conductor -> W6 series winding -> load.
    add_line(M, ph([M sprintf('/Main_W1W2_%d', k)], 'RConn', 1), ...
        ph([M sprintf('/Series_W5W6_%d', k)], 'RConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/Series_W5W6_%d', k)], 'RConn', 2), ...
        ph([M '/MeasLV'], 'LConn', k), 'autorouting', 'on');
    add_line(M, ph([M '/MeasLV'], 'RConn', k), ph([M '/Load'], 'LConn', k), ...
        'autorouting', 'on');

    % W3 is tapped from the primary side and magnetically feeds W4.
    add_line(M, ph([M sprintf('/Main_W1W2_%d', k)], 'LConn', 1), ...
        ph([M sprintf('/Flex_W3W4_%d', k)], 'LConn', 1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/Flex_W3W4_%d', k)], 'RConn', 1), ...
        ph([M '/MeasEnergy'], 'LConn', k), 'autorouting', 'on');
    add_line(M, ph([M '/MeasEnergy'], 'RConn', k), ...
        ph([M '/Energy_RL'], 'LConn', k), 'autorouting', 'on');
    add_line(M, ph([M '/Energy_RL'], 'RConn', k), ...
        ph([M '/EnergyConverter'], 'LConn', k), 'autorouting', 'on');

    % W5 is driven by one full H-bridge per phase; W6 is the line-side
    % series winding.
    add_line(M, ph([M sprintf('/Series_W5W6_%d', k)], 'LConn', 1), ...
        ph([M '/RegulatingConverter'], 'LConn', 2*k-1), 'autorouting', 'on');
    add_line(M, ph([M sprintf('/Series_W5W6_%d', k)], 'LConn', 2), ...
        ph([M '/RegulatingConverter'], 'LConn', 2*k), 'autorouting', 'on');
end

% Common/grounded neutral groups.
connect3(M, 'Main_W1W2', 'LConn', 2);
add_line(M, ph([M '/Main_W1W2_3'], 'LConn', 2), ...
    ph([M '/W1_neutral_ground'], 'LConn', 1), 'autorouting', 'on');

connect3(M, 'Main_W1W2', 'RConn', 2);
add_line(M, ph([M '/Main_W1W2_3'], 'RConn', 2), ...
    ph([M '/W2_neutral_ground'], 'LConn', 1), 'autorouting', 'on');

connect3(M, 'Flex_W3W4', 'LConn', 2);
add_line(M, ph([M '/Flex_W3W4_3'], 'LConn', 2), ...
    ph([M '/W3_neutral_ground'], 'LConn', 1), 'autorouting', 'on');

connect3(M, 'Flex_W3W4', 'RConn', 2);
add_line(M, ph([M '/Flex_W3W4_3'], 'RConn', 2), ...
    ph([M '/W4_neutral_ground'], 'LConn', 1), 'autorouting', 'on');

% Shared DC link and chopper.
dcPos = ph([M '/Cdc'], 'LConn', 1);
dcNeg = ph([M '/Cdc'], 'RConn', 1);
add_line(M, dcPos, ph([M '/EnergyConverter'], 'RConn', 1), 'autorouting', 'on');
add_line(M, ph([M '/EnergyConverter'], 'RConn', 2), dcNeg, 'autorouting', 'on');
add_line(M, dcPos, ph([M '/RegulatingConverter'], 'RConn', 1), 'autorouting', 'on');
add_line(M, ph([M '/RegulatingConverter'], 'RConn', 2), dcNeg, 'autorouting', 'on');
add_line(M, ph([M '/MeasVdc'], 'LConn', 1), dcPos, 'autorouting', 'on');
add_line(M, ph([M '/MeasVdc'], 'LConn', 2), dcNeg, 'autorouting', 'on');
add_line(M, dcPos, ph([M '/Chop'], 'LConn', 1), 'autorouting', 'on');
add_line(M, ph([M '/Chop'], 'RConn', 1), ph([M '/Rchop'], 'LConn', 1), ...
    'autorouting', 'on');
add_line(M, ph([M '/Rchop'], 'RConn', 1), dcNeg, 'autorouting', 'on');

% Signal wiring.
add_line(M, 'MeasVdc/1', 'Chop_cmp/1', 'autorouting', 'on');
add_line(M, 'Chop_gate/1', 'Chop_cmp/2', 'autorouting', 'on');
add_line(M, 'Chop_cmp/1', 'Chop/1', 'autorouting', 'on');
add_line(M, 'MeasMV/1', 'Vmv_abc/1', 'autorouting', 'on');
add_line(M, 'MeasMV/2', 'Igrid_abc/1', 'autorouting', 'on');
add_line(M, 'MeasLV/1', 'Vlv_abc/1', 'autorouting', 'on');
add_line(M, 'MeasLV/1', 'VoltageRegulator/1', 'autorouting', 'on');
add_line(M, 'MeasLV/1', 'HPTSACController/1', 'autorouting', 'on');
add_line(M, 'MeasMV/1', 'HPTSACController/5', 'autorouting', 'on');
add_line(M, 'VoltageRegulator/1', 'RegCommandSelect/3', 'autorouting', 'on');
add_line(M, 'HPTSACController/1', 'RegCommandSelect/1', 'autorouting', 'on');
add_line(M, 'SAC_enable/1', 'RegCommandSelect/2', 'autorouting', 'on');
add_line(M, 'RegCommandSelect/1', 'RegulatingConverter/1', 'autorouting', 'on');
add_line(M, 'RegCommandSelect/1', 'Mref6_cmd/1', 'autorouting', 'on');
add_line(M, 'VoltageRegulator/2', 'Mreg_cmd/1', 'autorouting', 'on');
add_line(M, 'MeasVdc/1', 'Vdc/1', 'autorouting', 'on');
add_line(M, 'MeasVdc/1', 'HPTSACController/2', 'autorouting', 'on');
add_line(M, 'MeasVdc/1', 'EnergyController/1', 'autorouting', 'on');
add_line(M, 'MeasEnergy/1', 'EnergyController/2', 'autorouting', 'on');
add_line(M, 'MeasEnergy/2', 'EnergyController/3', 'autorouting', 'on');
add_line(M, 'MeasEnergy/1', 'HPTSACController/3', 'autorouting', 'on');
add_line(M, 'MeasEnergy/2', 'HPTSACController/4', 'autorouting', 'on');
add_line(M, 'EnergyController/1', 'EnergyCommandSelect/3', 'autorouting', 'on');
add_line(M, 'HPTSACController/2', 'EnergyCommandSelect/1', 'autorouting', 'on');
add_line(M, 'SAC_energy_enable/1', 'EnergyCommandSelect/2', 'autorouting', 'on');
add_line(M, 'EnergyCommandSelect/1', 'EnergyConverter/1', 'autorouting', 'on');
add_line(M, 'EnergyCommandSelect/1', 'Menergy_cmd/1', 'autorouting', 'on');
add_line(M, 'EnergyController/2', 'Energy_dbg/1', 'autorouting', 'on');
add_line(M, 'MeasEnergy/1', 'Energy_Vabc/1', 'autorouting', 'on');
add_line(M, 'MeasEnergy/2', 'Energy_Iabc/1', 'autorouting', 'on');
add_line(M, 'HPTSACController/3', 'HPTSAC_obs/1', 'autorouting', 'on');
add_line(M, 'HPTSACController/4', 'HPTSAC_action/1', 'autorouting', 'on');

create_named_subsystem(M, 'MainTransformer', { ...
    'Main_W1W2_1', 'Main_W1W2_2', 'Main_W1W2_3', ...
    'W1_neutral_ground', 'W2_neutral_ground'});
create_named_subsystem(M, 'PrimaryEnergyCoupling', { ...
    'Flex_W3W4_1', 'Flex_W3W4_2', 'Flex_W3W4_3', ...
    'MeasEnergy', 'Energy_RL', 'W3_neutral_ground', 'W4_neutral_ground'});
create_named_subsystem(M, 'SecondarySeriesInjection', { ...
    'Series_W5W6_1', 'Series_W5W6_2', 'Series_W5W6_3'});
create_named_subsystem(M, 'DQControl', { ...
    'VoltageRegulator', 'EnergyController', 'HPTSACController', ...
    'SAC_enable', 'SAC_energy_enable', ...
    'RegCommandSelect', 'EnergyCommandSelect'});
create_named_subsystem(M, 'DCLink', { ...
    'Cdc', 'MeasVdc', 'Chop', 'Rchop', 'Chop_gate', 'Chop_cmp'});
create_named_subsystem(M, 'MeasurementAndLogging', { ...
    'Vmv_abc', 'Igrid_abc', 'Vlv_abc', 'Vdc', ...
    'Mreg_cmd', 'Mref6_cmd', 'Menergy_cmd', ...
    'Energy_Vabc', 'Energy_Iabc', 'Energy_dbg', ...
    'HPTSAC_obs', 'HPTSAC_action'});

decorate_model(M);
